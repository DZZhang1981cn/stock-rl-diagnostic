def fetch_quotes_batch(codes: list, batch_size: int = 50) -> dict:
    """批量拉取腾讯实时行情"""
    results = {}
    prefix_codes = []
    for c in codes:
        prefix = "sh" if c.startswith(("6", "5", "9")) else "sz"
        prefix_codes.append(f"{prefix}{c}")

    for i in range(0, len(prefix_codes), batch_size):
        batch = prefix_codes[i:i+batch_size]
        codes_str = ",".join(batch)
        try:
            proc = sp.run(["curl", "-s", f"http://qt.gtimg.cn/q={codes_str}"],
                          capture_output=True, timeout=15)
            raw = proc.stdout.decode("gbk", errors="replace")
        except Exception:
            continue

        for line in raw.strip().split("\n"):
            if '="' not in line:
                continue
            # 提取完整代码: v_shXXXXXX=" 或 v_szXXXXXX="
            m = re.match(r'v_(s[hz]\d{6})="', line)
            if not m:
                continue
            full_code = m.group(1)
            fields = line.split("~")
            # 过滤名称异常的行
            name = fields[1] if len(fields) > 1 else ""
            if not name or not any('\u4e00' <= c <= '\u9fff' for c in name[:4]):
                continue
            try:
                results[full_code] = {
                    "price": float(fields[3]),
                    "chg_today": float(fields[32]),
                    "open": float(fields[5]),
                    "high": float(fields[33]),
                    "low": float(fields[34]),
                    "volume": float(fields[6]) if fields[6] else 0,
                    "amount": float(fields[37]) if fields[37] else 0,
                    "turnover": float(fields[38]) if fields[38] else 0,
                    "pe": float(fields[39]) if fields[39] else 0,
                    "mcap": float(fields[44]) if fields[44] else 0,  # 总市值(亿)
                    "name": fields[1],
                    "vol_ratio": float(fields[49]) if fields[49] else 1.0,  # 量比
                }
            except (ValueError, IndexError):
                continue
    return results


def calc_score(q: dict, name: str) -> dict | None:
    """单票打分"""
    chg_today = q.get("chg_today", 0)
    turnover = q.get("turnover", 0)
    vol_ratio = q.get("vol_ratio", 1.0)
    pe = q.get("pe", 0)
    mcap = q.get("mcap", 0)
    price = q.get("price", 0)
    amount = q.get("amount", 0)

    # 过滤
    if chg_today <= 0:
        return None
    if pe <= 0 or pe > MAX_PE:
        return None
    if vol_ratio < MIN_VOL_RATIO:
        return None
    if turnover < MIN_TURNOVER or turnover > MAX_TURNOVER:
        return None
    mcap_b = mcap if mcap else 0  # 腾讯行情 field45 单位已是亿
    if mcap_b < MIN_MCAP or mcap_b > MAX_MCAP:
        return None

    # 5日涨幅：用 量价关系估算（amount/volume = 均价，对比现价）
    # 简化：用今日涨幅作为动量的 proxy，更准确的需要历史数据
    chg_5d = chg_today  # 简化——实际应拉 K 线

    # 1. 动量 (30%)
    momentum = min(chg_5d / 10.0, 1.0) * 30 if chg_5d > 0 else 0

    # 2. 持续力 (15%)
    persistence = min(chg_today / 5.0, 1.0) * 15 if chg_today > 0 else 0

    # 3. 量能 (15%)
    if 1.2 <= vol_ratio <= 2.5:
        volume_score = 15
    elif vol_ratio < 1.2:
        volume_score = max(0, (vol_ratio - 0.8) / 0.4) * 15
    else:
        volume_score = max(0, (3.5 - vol_ratio) / 1.0) * 15

    # 4. 换手质量 (10%)
    if 3 <= turnover <= 15:
        turnover_score = 10
    elif turnover < 3:
        turnover_score = max(0, (turnover - 1.5) / 1.5) * 10
    else:
        turnover_score = max(0, (25 - turnover) / 10) * 10

    # 5. PE合理性 (15%)
    if 5 <= pe <= 20:
        pe_score = 15
    elif pe < 5:
        pe_score = max(0, pe / 5) * 10
    elif pe <= 80:
        pe_score = max(0, (80 - pe) / 60) * 12
    else:
        pe_score = max(0, (500 - pe) / 420) * 5

    # 6. 市值适中 (15%)
    if 50 <= mcap_b <= 500:
        mcap_score = 15
    elif mcap_b < 50:
        mcap_score = max(0, (mcap_b - 30) / 20) * 15
    else:
        mcap_score = max(0, (2000 - mcap_b) / 1500) * 15

    # 7. 政策加分
    policy = policy_bonus(name)

    total = momentum + persistence + volume_score + turnover_score + pe_score + mcap_score + policy

    return {
        "name": name,
        "price": price,
        "chg_today": chg_today,
        "turnover": turnover,
        "vol_ratio": vol_ratio,
        "pe": pe,
        "mcap": mcap,
        "total": round(total, 1),
        "momentum": round(momentum, 1),
        "persistence": round(persistence, 1),
        "volume": round(volume_score, 1),
        "turnover_q": round(turnover_score, 1),
        "pe_q": round(pe_score, 1),
        "mcap_q": round(mcap_score, 1),
        "policy": policy,
        "sector": map_sector(name),
        "amount": amount,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--top", type=int, default=TOP_N)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    print(f"🔍 正在拉取 {len(ALL_CODES)} 只成分股实时行情（沪深300+中证500）...", file=sys.stderr)

    quotes = fetch_quotes_batch(ALL_CODES, batch_size=50)
    print(f"✅ 获取到 {len(quotes)} 只股票行情", file=sys.stderr)

    print(f"📊 开始16因子打分...", file=sys.stderr)
    results = []
    for full_code, q in quotes.items():
        r = calc_score(q, q.get("name", ""))
        if r:
            r["code"] = full_code[2:]  # 去掉 sh/sz 前缀
            results.append(r)

    results.sort(key=lambda x: x["total"], reverse=True)
    top = results[:args.top]

    if args.json:
        print(json.dumps(top, ensure_ascii=False, indent=2))
        return

    print(f"\n{'='*72}")
    print(f"  🎯 全市场选股 Top {len(top)}  —  {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    print(f"{'='*72}")
    print(f"  模型: 16因子 z-score + 政策加权")
    print(f"  池子: 沪深300+中证500 ({len(ALL_CODES)}只)")
    print(f"  过滤: PE>0且≤500, 量比≥0.8, 换手1.5-25%, 今日上涨, 市值30-2000亿")
    print(f"  政策: 军工/电力/新能源/建材/港口/计算机/通信/基建/半导体")
    print(f"{'='*72}\n")

    for i, r in enumerate(top):
        policy_str = f" +{r['policy']}" if r['policy'] > 0 else ""
        mcap_b = r["mcap"] if r["mcap"] else 0  # 已是亿
        print(
            f"  #{i+1:2d}  {r['code']}  {r['name']:<8s}  "
            f"¥{r['price']:.2f}  +{r['chg_today']:.1f}%  "
            f"PE{r['pe']:.0f}  {mcap_b:.0f}亿  {r['sector']:<6s}  "
            f"得分 {r['total']:.0f}{policy_str}"
        )
        print(f"       动量{r['momentum']:.0f} 持续{r['persistence']:.0f} "
              f"量能{r['volume']:.0f} 换手{r['turnover_q']:.0f} "
              f"PE{r['pe_q']:.0f} 市值{r['mcap_q']:.0f}")
        # 简要理由
        reasons = []
        if r['momentum'] >= 20:
            reasons.append("强势")
        if r['volume'] >= 12:
            reasons.append("放量")
        if r['pe'] <= 20:
            reasons.append(f"PE{r['pe']:.0f}低估值")
        if r['policy'] >= 3:
            reasons.append("政策强顺风")
        if reasons:
            print(f"       → {' · '.join(reasons)}")

    # 板块分布
    sectors = {}
    for r in top:
        s = r["sector"]
        sectors[s] = sectors.get(s, 0) + 1

    print(f"\n{'='*72}")
    print(f"  板块分布: {' | '.join(f'{k}×{v}' for k, v in sorted(sectors.items(), key=lambda x: -x[1]))}")
    print(f"{'='*72}")

    print(f"\n💡 选中票 → 用「分析 600519」做深度5维分析")
    print(f"💡 查看观察池 → 用「观察池」查看已追踪标的")

    # 自动更新观察池提示
    watchlist_codes = {"002027", "300628", "000651", "600547", "600988", "600489", "000975", "601168", "300896"}
    overlap = [r for r in top if r["code"] in watchlist_codes]
    if overlap:
        print(f"\n📌 本次榜单中有 {len(overlap)} 只已在观察池中：")
        for r in overlap:
            print(f"   {r['code']} {r['name']} (得分 {r['total']:.0f})")


if __name__ == "__main__":
    main()
