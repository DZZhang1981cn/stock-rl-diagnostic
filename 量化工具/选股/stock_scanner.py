def map_sector(name: str) -> str:
    for sector, kws in SECTOR_KW.items():
        for kw in kws:
            if kw in name:
                return sector
    return "其他"

def policy_bonus(name: str) -> int:
    sector = map_sector(name)
    bonus = 0
    for hot, weight in POLICY_HOT.items():
        if hot in sector:
            bonus = max(bonus, weight)
    for cold, weight in POLICY_COLD.items():
        if cold in sector:
            bonus = min(bonus, weight)
    return bonus

